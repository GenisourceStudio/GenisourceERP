#!/usr/bin/env bash
# First-run installer for a single-factory deployment.
#
# Generates .env with random secrets, builds the images and waits for the API to turn
# healthy. Safe to re-run: an existing .env is never overwritten, so upgrades keep their
# database password and JWT secret.
#
# Two layouts are supported:
#
#   * the repository (deploy/scripts/install.sh) — builds the images from source;
#   * an offline package (scripts/install.sh next to a compose.yaml and an images/
#     directory) — loads the images that were built elsewhere and never touches the
#     network.
#
# The layout is detected, not asked for: the offline package has a compose.yaml next to
# its scripts and no source tree, and the repository has the opposite.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PACKAGE_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"

if [ -f "$PACKAGE_DIR/compose.yaml" ] && [ -d "$PACKAGE_DIR/images" ]; then
  ROOT="$PACKAGE_DIR"
  OFFLINE="true"
else
  ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
  OFFLINE="false"
fi
cd "$ROOT"

CN_MIRROR="false"
for arg in "$@"; do
  case "$arg" in
    --cn-mirror) CN_MIRROR="true" ;;
    -h|--help)
      cat <<'USAGE'
Usage: ./deploy/scripts/install.sh [--cn-mirror]

  --cn-mirror   use Aliyun Maven and npmmirror registry (mainland China)
USAGE
      exit 0
      ;;
    *)
      echo "Unknown option: $arg" >&2
      exit 2
      ;;
  esac
done

if ! command -v docker >/dev/null 2>&1; then
  echo "Docker is required but was not found in PATH." >&2
  exit 1
fi
if ! docker compose version >/dev/null 2>&1; then
  echo "Docker Compose v2 is required (docker compose)." >&2
  exit 1
fi

random_secret() {
  # 32+ bytes, URL-safe, no quotes or backslashes so it drops into .env untouched.
  openssl rand -base64 48 | tr -d '\n=+/' | cut -c1-40
}

if [ -f .env ]; then
  echo "==> .env already exists, keeping existing secrets"
else
  ADMIN_PASSWORD="$(random_secret | cut -c1-16)"
  DB_PASSWORD="$(random_secret)"
  JWT_SECRET="$(random_secret)$(random_secret)"

  if [ "$CN_MIRROR" = "true" ]; then
    MAVEN_MIRROR="aliyun"
    NPM_REGISTRY="https://registry.npmmirror.com"
  else
    MAVEN_MIRROR="central"
    NPM_REGISTRY="https://registry.npmjs.org"
  fi

  cat > .env <<EOF
# Generated by deploy/scripts/install.sh on $(date '+%Y-%m-%d %H:%M:%S').
# Keep this file out of version control.

WEB_PORT=8080

DB_NAME=genisource_erp
DB_USER=erp
DB_PASSWORD=${DB_PASSWORD}

ERP_ADMIN_USERNAME=admin
ERP_ADMIN_PASSWORD=${ADMIN_PASSWORD}
ERP_FORCE_PASSWORD_CHANGE=true

ERP_JWT_SECRET=${JWT_SECRET}

ERP_TENANT_MODE=single
ERP_DEFAULT_TENANT=default

SPRING_PROFILES_ACTIVE=demo

MES_BASE_URL=
MES_CLIENT_ID=
MES_CLIENT_SECRET=
MES_SYNC_ENABLED=false

MAVEN_MIRROR=${MAVEN_MIRROR}
NPM_REGISTRY=${NPM_REGISTRY}
EOF

  chmod 600 .env
  echo "==> Wrote .env with generated secrets (mode 600)"
  echo "    Initial administrator: admin / ${ADMIN_PASSWORD}"
  echo "    Change it on first login; the password above is printed only once."
fi

if [ "$OFFLINE" = "true" ]; then
  echo "==> Loading the images from the offline package"
  for archive in images/*.tar; do
    [ -e "$archive" ] || continue
    echo "    loading $(basename "$archive")"
    gzip -dc "$archive" | docker load
  done

  # The compose file points at the images the package carries, so nothing is built here.
  # Overriding the build context is what keeps `docker compose up` from trying to
  # compile a source tree this machine does not have.
  echo "==> Starting containers (first run takes 2-5 minutes)"
  docker compose up -d
else
  echo "==> Building and starting containers (first run takes 3-10 minutes)"
  docker compose up -d --build
fi

echo "==> Waiting for the API to become healthy"
WEB_PORT_VALUE="$(grep -E '^WEB_PORT=' .env | cut -d= -f2)"
WEB_PORT_VALUE="${WEB_PORT_VALUE:-8080}"

for attempt in $(seq 1 90); do
  if curl -fsS --noproxy '*' "http://127.0.0.1:${WEB_PORT_VALUE}/actuator/health" 2>/dev/null | grep -q '"status":"UP"'; then
    echo ""
    echo "Genisource ERP is up:"
    echo "  Console   http://localhost:${WEB_PORT_VALUE}"
    echo "  API docs  http://localhost:${WEB_PORT_VALUE}/swagger-ui.html"
    echo "  Health    http://localhost:${WEB_PORT_VALUE}/actuator/health"
    echo ""
    echo "Next: sign in and change the administrator password."
    exit 0
  fi

  if [ "$attempt" -eq 90 ]; then
    echo ""
    echo "The API did not become healthy within 15 minutes." >&2
    echo "Inspect the logs with: docker compose logs --tail=200 app" >&2
    exit 1
  fi
  sleep 10
done
